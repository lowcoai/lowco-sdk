const header = "Code generated by tools/apigen from specs/lowco-api.json (Lowco API %s). DO NOT EDIT."

func tsType(t *Type) string {
	var s string
	switch t.Kind {
	case "ref":
		s = t.Ref
	case "object":
		if t.Name != "" {
			s = t.Name
		} else {
			s = "Record<string, unknown>"
		}
	case "array":
		s = tsType(t.Items) + "[]"
		if strings.Contains(tsType(t.Items), " ") {
			s = "Array<" + tsType(t.Items) + ">"
		}
	case "map":
		s = "Record<string, " + tsType(t.Values) + ">"
	case "string":
		s = "string"
	case "integer", "number":
		s = "number"
		if len(t.IntEnum) > 0 {
			var vs []string
			for _, v := range t.IntEnum {
				vs = append(vs, fmt.Sprint(v))
			}
			s = strings.Join(vs, " | ")
		}
	case "boolean":
		s = "boolean"
	case "enum":
		var vs []string
		for _, v := range t.Enum {
			vs = append(vs, fmt.Sprintf("%q", v))
		}
		s = strings.Join(vs, " | ")
	case "union":
		var vs []string
		for _, u := range t.Union {
			vs = append(vs, tsType(u))
		}
		s = strings.Join(vs, " | ")
	case "file":
		s = "FileInput"
	default:
		s = "unknown"
	}
	if t.Nullable && s != "unknown" {
		s += " | null"
	}
	return s
}

func tsDoc(b *strings.Builder, indent, desc string) {
	desc = strings.TrimSpace(desc)
	if desc == "" {
		return
	}
	desc = strings.ReplaceAll(desc, "*/", "*\\/")
	b.WriteString(indent + "/** " + strings.ReplaceAll(desc, "\n", " ") + " */\n")
}

func tsProp(name string) string {
	for _, r := range name {
		if !(r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			return fmt.Sprintf("%q", name)
		}
	}
	return name
}

// fileSpec describes where an operation's file inputs are.
func fileSpec(o *Op) string {
	extra := "[]"
	if len(o.Extra) > 0 {
		var q []string
		for _, x := range o.Extra {
			q = append(q, fmt.Sprintf("%q", x))
		}
		extra = "[" + strings.Join(q, ", ") + "]"
	}
	return fmt.Sprintf(`{ input: %q, extra: %s }`, o.Input, extra)
}

func emitTS(m *Model) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "// "+header+"\n\n", m.Version)
	b.WriteString("import type { Answer, CallOptions, Core, FileInput, RequestOptions, WaitOptions } from \"./core.js\";\n\n")
	fmt.Fprintf(&b, "/** The Lowco API version these types were generated from. */\nexport const API_VERSION = %q;\n\n", m.Version)

	b.WriteString("/** Every error.reason the API can answer (docs.lowco.ai/api/errors). */\nexport type ErrorReason =\n")
	for i, r := range m.Reasons {
		sep := ""
		if i == len(m.Reasons)-1 {
			sep = ";"
		}
		fmt.Fprintf(&b, "  | %q%s\n", r.Name, sep)
	}
	b.WriteString("\n/** Each reason's HTTP status, when it is answered and what to do. */\nexport const ERROR_REASONS: Record<ErrorReason, { status: number; when: string; action: string }> = {\n")
	for _, r := range m.Reasons {
		fmt.Fprintf(&b, "  %s: { status: %d, when: %q, action: %q },\n", r.Name, r.Status, r.When, r.Action)
	}
	b.WriteString("};\n\n")

	for _, name := range m.typeNames() {
		t := m.Types[name]
		tsDoc(&b, "", t.Desc)
		switch t.Kind {
		case "object":
			fmt.Fprintf(&b, "export interface %s {\n", name)
			for _, f := range t.Fields {
				tsDoc(&b, "  ", f.Desc)
				opt := "?"
				if f.Required {
					opt = ""
				}
				fmt.Fprintf(&b, "  %s%s: %s;\n", tsProp(f.Name), opt, tsType(f.Type))
			}
			b.WriteString("}\n\n")
		default:
			fmt.Fprintf(&b, "export type %s = %s;\n\n", name, tsType(t))
		}
	}

	for _, svc := range m.services() {
		cls := pascal(svc) + "Operations"
		fmt.Fprintf(&b, "/** /v1/%s operations. */\nexport class %s {\n  constructor(private readonly core: Core) {}\n\n", svc, cls)
		for _, o := range m.Ops {
			if o.Service != svc {
				continue
			}
			doc := o.Summary + ". " + modeNote(o) + " Meter " + o.Meter + "; scope " + o.Scope + "."
			tsDoc(&b, "  ", doc)
			fmt.Fprintf(&b, "  %s(params: %s, options?: CallOptions): Promise<Answer<%s>> {\n", camel(o.Name), o.Params.Name, o.Result)
			fmt.Fprintf(&b, "    return this.core.operation<%s>(%q, params as unknown as Record<string, unknown>, %s, options);\n  }\n\n", o.Result, o.Path, fileSpec(o))
		}
		b.WriteString("}\n\n")
	}

	for _, g := range m.groups() {
		cls := pascal(g) + "Resource"
		fmt.Fprintf(&b, "/** %s. */\nexport class %s {\n  constructor(private readonly core: Core) {}\n\n", groupDoc(g), cls)
		for _, e := range m.Endpoints {
			if e.Group != g {
				continue
			}
			var args, pathExpr []string
			for _, p := range e.PathParams {
				args = append(args, camel(p)+": string")
			}
			path := e.Path
			for _, p := range e.PathParams {
				path = strings.Replace(path, "{"+p+"}", "${encodeURIComponent("+camel(p)+")}", 1)
			}
			pathExpr = append(pathExpr, "`"+path+"`")
			result := "unknown"
			if e.Result != nil {
				result = tsType(e.Result)
			}
			tsDoc(&b, "  ", e.Summary+".")
			switch {
			case e.Multipart:
				fmt.Fprintf(&b, "  %s(file: FileInput, options?: RequestOptions): Promise<%s> {\n    return this.core.upload<%s>(%s, file, options);\n  }\n\n", e.Method, result, result, pathExpr[0])
				continue
			case e.Redirect:
				fmt.Fprintf(&b, "  %s(%s, options?: RequestOptions): Promise<string> {\n    return this.core.redirect(%s, options);\n  }\n\n", e.Method, strings.Join(args, ", "), pathExpr[0])
				continue
			}
			if e.Body != nil {
				args = append(args, "body: "+tsType(e.Body))
			}
			if e.Query != nil {
				q := "query?: " + e.Query.Name
				if hasRequired(e.Query) {
					q = "query: " + e.Query.Name
				}
				args = append(args, q)
			}
			args = append(args, "options?: RequestOptions")
			body := "undefined"
			if e.Body != nil {
				body = "body"
			}
			query := "undefined"
			if e.Query != nil {
				query = "query as unknown as Record<string, unknown> | undefined"
			}
			fmt.Fprintf(&b, "  %s(%s): Promise<%s> {\n    return this.core.call<%s>(%q, %s, { query: %s, json: %s }, options);\n  }\n\n",
				e.Method, strings.Join(args, ", "), result, result, e.HTTP, pathExpr[0], query, body)
			if e.Paged != nil {
				item := tsType(e.Paged)
				var pargs []string
				for _, p := range e.PathParams {
					pargs = append(pargs, camel(p)+": string")
				}
				qtype := "Record<string, unknown>"
				if e.Query != nil {
					qtype = "Omit<" + e.Query.Name + ", \"cursor\">"
				}
				pargs = append(pargs, "query?: "+qtype, "options?: RequestOptions")
				tsDoc(&b, "  ", "Every item of "+e.Method+", page after page (follows next_cursor).")
				fmt.Fprintf(&b, "  %sAll(%s): AsyncIterable<%s> {\n    return this.core.paginate<%s>(%s, query as unknown as Record<string, unknown> | undefined, options);\n  }\n\n",
					e.Method, strings.Join(pargs, ", "), item, item, pathExpr[0])
			}
		}
		switch g {
		case "jobs":
			b.WriteString("  /** Waits until the job is succeeded, failed or cancelled, polling with the Retry-After the API sends; throws LowcoApiError when it failed or was cancelled, LowcoTimeoutError at the timeout. */\n")
			b.WriteString("  wait(jobId: string, options?: WaitOptions): Promise<Job> {\n    return this.core.waitForJob(jobId, options);\n  }\n\n")
		case "files":
			b.WriteString("  /** Downloads a file object's signed url (no API key needed). */\n")
			b.WriteString("  download(url: string, options?: RequestOptions): Promise<Uint8Array> {\n    return this.core.download(url, options);\n  }\n\n")
		}
		b.WriteString("}\n\n")
	}

	b.WriteString("/** Every operation and resource of the Lowco API. */\nexport class GeneratedClient {\n")
	for _, svc := range m.services() {
		fmt.Fprintf(&b, "  /** /v1/%s operations. */\n  readonly %s: %sOperations;\n", svc, camel(svc), pascal(svc))
	}
	for _, g := range m.groups() {
		fmt.Fprintf(&b, "  /** %s. */\n  readonly %s: %sResource;\n", groupDoc(g), camel(g), pascal(g))
	}
	b.WriteString("\n  constructor(protected readonly core: Core) {\n")
	for _, svc := range m.services() {
		fmt.Fprintf(&b, "    this.%s = new %sOperations(core);\n", camel(svc), pascal(svc))
	}
	for _, g := range m.groups() {
		fmt.Fprintf(&b, "    this.%s = new %sResource(core);\n", camel(g), pascal(g))
	}
	b.WriteString("  }\n}\n")
	return []byte(b.String())
}

func hasRequired(t *Type) bool {
	for _, f := range t.Fields {
		if f.Required {
			return true
		}
	}
	return false
}

func modeNote(o *Op) string {
	if o.DefaultMode == "async" {
		return "Always asynchronous: answers 202 with a job."
	}
	return "Answers 200 inline, or 202 with a job above its sync limit (or with mode async)."
}

func groupDoc(g string) string {
	return map[string]string{
		"files": "Uploaded and produced files", "jobs": "Asynchronous jobs", "webhooks": "Webhook endpoints and deliveries",
		"templates": "Stored render templates", "settings": "Environment settings", "usage": "Usage and balance", "audit": "Console audit log",
	}[g]
}
